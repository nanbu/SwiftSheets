#!/usr/bin/env python3
"""Builds the spec feature matrix per format — one source, two products.

    python3 scripts/build-spec-feature-matrix.py            # rebuild the HTML and the YAML under docs/
    python3 scripts/build-spec-feature-matrix.py --check    # do the products match the source? (for CI; exit 1 on a difference)

The only source is scripts/spec-feature-matrix.json. docs/spec-feature-matrix.html and
docs/spec-feature-matrix.yaml are generated, so do not edit them by hand (two places fixed by hand always drift apart).
The look borrows the <style> of docs/format-support.html as it is — it is not copied here, so that the look of
the sibling documents cannot drift apart on its own.

Runs on the standard library alone (no external YAML library).
"""
import json
import os
import re
import sys
import html
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "scripts", "spec-feature-matrix.json")
STYLE_FROM = os.path.join(ROOT, "docs", "format-support.html")
OUT_HTML = os.path.join(ROOT, "docs", "spec-feature-matrix.html")
OUT_YAML = os.path.join(ROOT, "docs", "spec-feature-matrix.yaml")

ORDER = ["full", "partial", "preserved", "none", "na", "unverified"]
CELL_CLASS = {"full": "y", "partial": "h", "preserved": "", "none": "n", "na": "", "unverified": "h"}
EVIDENCE_LABEL = {"measured": "measured", "code": "code check", "readme": "document",
                  "judge": "judged by the application"}


def e(s):
    return html.escape(str(s), quote=True)


def code(s):
    return "<code>%s</code>" % e(s)


def counts(fmt, side):
    return Counter(r[side] for a in fmt["areas"] for r in a["features"])


def rows_of(fmt):
    return sum(len(a["features"]) for a in fmt["areas"])


# ------------------------------------------------------------------ YAML
def q(s):
    """A double-quoted YAML string. JSON string notation can be used as it is."""
    return json.dumps(s, ensure_ascii=False)


# Put the UTF-8 mark (BOM) at the head of the YAML. The reason lies on the display side: HTML can declare its
# encoding with <meta charset>, but a text file that is not HTML has nowhere to declare it, so the browser looks at
# the server's Content-Type. GitHub Pages serves .yaml as "text/yaml" (with no charset), so the browser guesses
# Latin-1 and non-ASCII text garbles. With a BOM at the head, the browser decides on UTF-8. YAML 1.2 explicitly
# allows a leading BOM (§5.2 Character Encodings), and libyaml-based implementations skip it (confirmed with
# Ruby/Psych).
# **Do not remove it** — without it, readers who open the file from the published page see garbled text.
BOM = "\ufeff"


def emit_yaml(d):
    meta, out = d["meta"], []
    w = out.append
    w("# " + meta["title"])
    w("# Generated. Edit scripts/spec-feature-matrix.json and")
    w("# run scripts/build-spec-feature-matrix.py (do not edit this file by hand).")
    w("meta:")
    for k in ("title", "library_version", "as_of", "commit", "axis", "granularity", "caveat"):
        w("  %s: %s" % (k, q(meta[k])))
    w("  environments:")
    for x in meta["environments"]:
        w("    - %s" % q(x))
    w("  status_vocabulary:")
    for key, v in meta["status_vocabulary"].items():
        w("    %s:" % key)
        w("      symbol: %s" % q(v["symbol"]))
        w("      meaning: %s" % q(v["meaning"]))
    w("  evidence_types:")
    for key, v in meta["evidence_types"].items():
        w("    %s: %s" % (key, q(v)))
    w("  common_api:")
    for key, v in meta["common_api"].items():
        w("    %s: %s" % (key, q(v)))
    w("")
    w("formats:")
    for f in d["formats"]:
        w("  - id: %s" % q(f["id"]))
        w("    name: %s" % q(f["name"]))
        w("    spec:")
        w("      name: %s" % q(f["spec"]["name"]))
        w("      public: %s" % ("true" if f["spec"]["public"] else "false"))
        w("      note: %s" % q(f["spec"]["note"]))
        w("    totals:")
        for side in ("read", "write"):
            c = counts(f, side)
            w("      %s: {%s}" % (side, ", ".join("%s: %d" % (k, c[k]) for k in ORDER)))
        w("      rows: %d" % rows_of(f))
        w("    areas:")
        for a in f["areas"]:
            w("      - id: %s" % q(a["id"]))
            w("        name: %s" % q(a["name"]))
            w("        features:")
            for r in a["features"]:
                w("          - id: %s" % q(r["id"]))
                w("            name: %s" % q(r["name"]))
                w("            spec_anchor: %s" % q(r["spec_anchor"]))
                w("            read: %s" % q(r["read"]))
                w("            write: %s" % q(r["write"]))
                if r["api"]:
                    w("            api:")
                    for x in r["api"]:
                        w("              - %s" % q(x))
                else:
                    w("            api: []")
                w("            warning: %s" % (q(r["warning"]) if r["warning"] else "null"))
                w("            evidence: %s" % q(r["evidence"]))
                w("            note: %s" % (q(r["note"]) if r["note"] else "null"))
    return BOM + "\n".join(out) + "\n"


