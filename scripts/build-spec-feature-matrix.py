    w("<h1>The spec feature matrix</h1>")
    w('<p class="lede">The features that the <strong>public specifications</strong> of Excel, OpenDocument and Numbers '
      "each have, set out in %d rows: whether SwiftSheets reads each one, whether it writes it, and which API reaches it. "
      "Where the sibling <a href=\"format-support.html\">format support table</a> measures \"the model's 48 features → 3 formats\", "
      "this table looks the <strong>other way round</strong>: \"a format's specification → SwiftSheets\".</p>" % total)
