def status_cell(meta, value):
    sym = meta["status_vocabulary"][value]["symbol"]
    cls = CELL_CLASS[value]
    return '<td class="m%s">%s</td>' % ((" " + cls) if cls else "", e(sym))


def format_table(meta, f):
    out = ['<div class="tablewrap"><table>']
    out.append("<thead><tr><th>Feature</th><th class=\"m\">Read</th><th class=\"m\">Write</th>"
               "<th>Where in the spec</th><th>API</th><th>Note (what is reported when it is dropped; evidence)</th></tr></thead><tbody>")
    for a in f["areas"]:
        out.append('<tr class="group"><td colspan="6">%s</td></tr>' % e(a["name"]))
        for r in a["features"]:
            note = []
            if r["warning"]:
                note.append("<strong>Warning</strong>: " + e(r["warning"]))
            if r["note"]:
                note.append(e(r["note"]))
            note.append('<span class="chip">%s</span>' % e(EVIDENCE_LABEL[r["evidence"]]))
            anchor = code(r["spec_anchor"]) if r["spec_anchor"] not in ("—", "") else "—"
            api = " ".join(code(x) for x in r["api"]) if r["api"] else "—"
            out.append("<tr><td>%s</td>%s%s<td>%s</td><td>%s</td><td>%s</td></tr>"
                       % (e(r["name"]), status_cell(meta, r["read"]), status_cell(meta, r["write"]),
                          anchor, api, " ".join(note)))
    out.append("</tbody></table></div>")
    return "\n".join(out)


def counts_table(d):
    out = ['<div class="tablewrap"><table>',
           "<thead><tr><th>Format</th><th>Direction</th>"
           + "".join('<th class="m">%s</th>' % e(d["meta"]["status_vocabulary"][k]["symbol"]) for k in ORDER)
           + '<th class="m">Rows</th></tr></thead><tbody>']
    for f in d["formats"]:
        total = rows_of(f)
        for side, label in (("read", "Read"), ("write", "Write")):
            c = counts(f, side)
            out.append("<tr><td>%s</td><td>%s</td>%s<td class=\"m\">%d</td></tr>"
                       % (e(f["name"]), label,
                          "".join('<td class="m">%d</td>' % c[k] for k in ORDER), total))
    out.append("</tbody></table></div>")
    return "\n".join(out)


def load_style():
    with open(STYLE_FROM, encoding="utf-8") as fh:
        m = re.search(r"<style>(.*?)</style>", fh.read(), re.S)
    if not m:
        sys.exit("❌ cannot extract the <style> from %s" % STYLE_FROM)
    return m.group(1)


def short_format_name(name):
    """The format name without its parenthesised extensions: "Excel (.xlsx / .xlsm)" -> "Excel"."""
    return re.split(r"\s*[(\uff08]", name, maxsplit=1)[0]


